-- Run this in Supabase Dashboard > SQL Editor for the storefront project.
-- This stores aggregate storefront events only; do not put customer name, phone, or address here.

create table if not exists public.store_analytics (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  event_type text not null check (event_type in (
    'page_view','product_view','add_to_cart','checkout_started','payment_redirect','order_placed','product_ordered'
  )),
  page text not null default '/',
  product_id text not null default '',
  product_name text not null default '',
  session_id text not null default ''
);

create index if not exists store_analytics_created_at_idx on public.store_analytics (created_at desc);
create index if not exists store_analytics_event_type_idx on public.store_analytics (event_type);
create index if not exists store_analytics_session_id_idx on public.store_analytics (session_id);

alter table public.store_analytics enable row level security;

-- Visitors may add event rows, but cannot read them. The CHECK constraint limits event names.
drop policy if exists "Public can submit storefront analytics" on public.store_analytics;
create policy "Public can submit storefront analytics"
  on public.store_analytics for insert
  to anon, authenticated
  with check (event_type in ('page_view','product_view','add_to_cart','checkout_started','payment_redirect','order_placed','product_ordered'));

-- Signed-in users can read analytics. Keep Supabase public sign-ups disabled so only your
-- manually created admin account can sign in. For stricter isolation, replace this policy
-- with one checking your exact admin auth.uid().
drop policy if exists "Authenticated admin can read storefront analytics" on public.store_analytics;
create policy "Authenticated admin can read storefront analytics"
  on public.store_analytics for select
  to authenticated
  using (auth.role() = 'authenticated');
